    public void buscarLibros()
    {
        List<Libro> libros = getLibros();

        ModeloTablaLibros m = (ModeloTablaLibros) tablaLibros.getModel();
        m.setFilas(libros);

        if (m.getRowCount() > 0)
        {
            tablaLibros.setRowSelectionInterval(0, 0);
            btnEditarLibro.setEnabled(true);
        }
        else
        {
            btnEditarLibro.setEnabled(false);
        }
    }

    private List<Libro> getLibros()
    {
        Integer id = null;
        if (!buscaId.getText().isEmpty())
        {
            id = Integer.parseInt(buscaId.getText());
        }

        return fa.obtenerLibros(id, buscaTitulo.getText(), buscaIsbn.getText(), buscaAutor.getText());
    }


